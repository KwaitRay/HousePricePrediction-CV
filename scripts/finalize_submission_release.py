"""Finalize the assembled snapshot, verify hashes, and create the two hand-in ZIPs."""
from pathlib import Path
import hashlib
import json
import os
import shutil
import subprocess
import sys
import zipfile

REPO=Path(__file__).resolve().parents[1]
DEST=REPO/'submission'
CODE=DEST/'English/code'


def sha(p):return hashlib.sha256(p.read_bytes()).hexdigest()
def put(path,data):
    if os.name=='nt' and len(str(path))>235:path=Path('\\\\?\\'+str(path))
    path.parent.mkdir(parents=True,exist_ok=True)
    path.write_bytes(data if isinstance(data,bytes) else data.encode('utf-8'))


def make_zip(folder,path,exclude=()):
    with zipfile.ZipFile(path,'w',zipfile.ZIP_DEFLATED,compresslevel=6) as z:
        for p in sorted(folder.rglob('*')):
            if p.is_file() and p not in exclude:
                z.write(p,p.relative_to(folder).as_posix())
    with zipfile.ZipFile(path) as z:assert z.testzip() is None


def main():
    # Preserve local provenance as data, not as a nonexistent Hugging Face download.
    metadata=json.loads((CODE/'pretrained_downloads.json').read_text(encoding='utf-8'))
    for model in metadata:
        for entry in model['files']:
            if entry['filename']=='download.json':
                src=REPO/model['local_dir']/entry['filename']
                assert sha(src)==entry['sha256']
                put(CODE/model['local_dir']/entry['filename'],src.read_bytes())
                entry['origin']='bundled_local_provenance'
    put(CODE/'pretrained_downloads.json',json.dumps(metadata,indent=2)+'\n')
    put(CODE/'download_pretrained_weights.py',DOWNLOAD)
    recipe=json.loads((CODE/'final_recipe.json').read_text(encoding='utf-8'))
    for c in recipe['components']:
        family,key=c['cache_family'],c['cache_key']
        manifest=json.loads((REPO/'.local/cache'/family/key/'manifest.json').read_text(encoding='utf-8'))
        if 'original_cache_key' in manifest:
            origin='pe_core_features' if family=='pe_core_multiview' else 'pe_core_giant_features'
            for name in ['manifest.json','chunk_sha256.json']:
                src=REPO/'.local/cache'/origin/manifest['original_cache_key']/name
                if src.exists():put(CODE/'.local/cache'/origin/manifest['original_cache_key']/name,src.read_bytes())
        # Relevant frozen-encoder registrations used by the historical adapters.
        folder=REPO/'output/experiment_record'/c['source'].replace('\\','/')
        for p in folder.glob('*.json'):put(CODE/p.relative_to(REPO),p.read_bytes())
    # Reusable source for the result checker and original occlusion experiment.
    for name in ['evaluate_report.py','verify_submission.py']:
        support=REPO/'scripts/submission_support'/name
        if support.exists():put(CODE/name,support.read_bytes())
        else:put(support,(CODE/name).read_bytes())
    occlusion=CODE/'report_analysis/occlusion_experiment_original.py'
    # Retain the original project-relative depth expected by this historical script.
    put(CODE/'submission/report/build_occlusion_figures.py',occlusion.read_bytes())
    put(CODE/'submission/report/README.txt',
        'Original occlusion-study source; historical project paths. For CPU-only figure rebuilding use report_analysis/build_panels.py.\n')
    # Checks do not execute encoders or train neural networks.
    subprocess.run([sys.executable,'-X','utf8','evaluate_report.py'],cwd=CODE,check=True)
    # Remove only generated bytecode directories within the new snapshot.
    for p in list(CODE.rglob('__pycache__')):
        resolved=p.resolve()
        assert resolved.is_relative_to(CODE.resolve()) and p.name=='__pycache__'
        shutil.rmtree(resolved)
    files={p.relative_to(CODE).as_posix():{'bytes':p.stat().st_size,'sha256':sha(p)}
           for p in sorted(CODE.rglob('*')) if p.is_file() and p.name!='MANIFEST.json'}
    put(CODE/'MANIFEST.json',json.dumps(files,indent=2)+'\n')
    subprocess.run([sys.executable,'-X','utf8','verify_submission.py'],cwd=CODE,check=True)
    from pypdf import PdfReader
    pages={}
    for name in ['English','Chinese']:
        reader=PdfReader(DEST/name/'report.pdf');pages[name]=len(reader.pages)
        text='\n'.join(p.extract_text() or '' for p in reader.pages)
        assert all(value in text for value in ['Shifeng Chen','Haoxuan Ying','1686631','1255329'])
        assert 'Group member' not in text and '[学号' not in text
        assert len(reader.pages)<=5
        if name=='English':assert len(reader.pages)==5 and reader.pages[4].extract_text().strip().startswith('REFERENCES')
    codezip=DEST/'English/code.zip'
    if codezip.exists():raise FileExistsError(codezip)
    make_zip(CODE,codezip)
    allzip=DEST/'English_all_materials.zip'
    if allzip.exists():raise FileExistsError(allzip)
    make_zip(DEST/'English',allzip)
    write={'branch':'feat/submission','authors':recipe['authors'],'files':{},'validation':{
        'pdf_pages':pages,'english_content_pages':4,'test_predictions':3000,
        'fitted_models_included':False,'pretrained_weights_included':False,
        'feature_arrays_included':False,'provided_images_included':False,
        'numerical_checks':'English/code/checks/report_metrics.json','manifest_files':len(files),
        'zip_crc_checked':True,'gpu_execution':False}}
    for p in [codezip,allzip,DEST/'English/report.pdf',DEST/'Chinese/report.pdf']:
        write['files'][p.relative_to(DEST).as_posix()]={'bytes':p.stat().st_size,'sha256':sha(p)}
    put(DEST/'release_manifest.json',json.dumps(write,ensure_ascii=False,indent=2)+'\n')
    print(json.dumps(write,ensure_ascii=False,indent=2))



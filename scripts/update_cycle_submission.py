"""Update source/evidence/portable entry, reverify code.zip, then refresh reports."""
from pathlib import Path
import hashlib
import json
import shutil
import subprocess
import sys
import zipfile

ROOT=Path(__file__).resolve().parents[1]
REPORT=ROOT.parent/'submission/report'
CODE=ROOT/'submission/English/code'


def sha(path):return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    shutil.copyfile(ROOT/'scripts/submission_support/reproduce_final.py',CODE/'reproduce_final.py')
    for p in (REPORT/'figures/analysis_sources').glob('*'):
        if p.is_file() and p.suffix in {'.csv','.json'}:shutil.copyfile(p,CODE/'report_analysis/figures/analysis_sources'/p.name)
    for stem in ['report_success_failure_cases','report_regional_and_outcome_cases']:
        for ext in ['pdf','png','svg']:shutil.copyfile(REPORT/f'figures/{stem}.{ext}',CODE/f'report_analysis/figures/{stem}.{ext}')
    shutil.copyfile(REPORT/'figures/analysis_sources/report_compact_results_table.csv',CODE/'report_analysis/representative_results.csv')
    source=(REPORT/'build_cycle_evidence.py').read_text(encoding='utf-8')
    source=source.replace('import hashlib','import os\nimport hashlib',1)
    source=source.replace("REPO=ROOT.parents[1]/'cv-house-price'",'REPO=ROOT.parent')
    source=source.replace("LOCAL=REPO/'.local/experiment_record'","LOCAL=REPO/'evidence/components'")
    source=source.replace("final=LOCAL/'15_fixed_ensembles/pe_whole_pca_incremental_fusion/20261015T033810Z_8aa6ec62/predictions.csv'","final=REPO/'evidence/final_validation_predictions.csv'")
    source=source.replace("settings=json.loads((REPO/'local_paths.json').read_text(encoding='utf-8'))","settings=json.loads((REPO/('local_paths.json' if (REPO/'local_paths.json').exists() else 'local_paths.example.json')).read_text(encoding='utf-8'))")
    source=source.replace("data_root=Path(settings['data_root'])/'train'","data_root=Path(os.environ.get('CV_DATA_ROOT',str(REPO/settings['data_root'])))/'train'")
    source=source.replace('str(p.relative_to(REPO.parent))','str(p)')
    (CODE/'report_analysis/build_cycle_evidence.py').write_text(source,encoding='utf-8')
    shutil.copyfile(REPORT/'build_single_column_table.py',CODE/'report_analysis/build_single_column_table.py')
    shutil.copyfile(REPORT/'build_augmentation_table.py',CODE/'report_analysis/build_augmentation_table.py')
    shutil.copyfile(REPORT/'build_fig3_response_summary.py',CODE/'report_analysis/build_fig3_response_summary.py')
    panels=(REPORT/'build_report_analysis_panels.py').read_text(encoding='utf-8')
    panels=panels.replace('import hashlib','import os\nimport hashlib',1)
    panels=panels.replace('ASSIGNMENT = ROOT.parents[1]','ASSIGNMENT = ROOT.parent').replace("REPO = ASSIGNMENT / 'cv-house-price'",'REPO = ROOT.parent')
    import re
    panels=re.sub(r"PRED = REPO / .*", "PRED = REPO / 'evidence/final_validation_predictions.csv'",panels,count=1)
    panels=panels.replace("DATA = ASSIGNMENT / 'comp-90086-2026/house_dataset/train'","DATA = Path(os.environ.get('CV_DATA_ROOT',str(REPO/'dataset')))/'train'")
    panels=panels.replace('str(p.relative_to(ASSIGNMENT))','str(p)')
    (CODE/'report_analysis/build_panels.py').write_text(panels,encoding='utf-8')
    for stem in ['report_prediction_scatter_price_band_errors','report_pca_distance_bandwidth_oof']:
        for ext in ['png','svg','pdf']:shutil.copyfile(REPORT/f'figures/{stem}.{ext}',CODE/f'report_analysis/figures/{stem}.{ext}')
    readme=(CODE/'README.txt').read_text(encoding='utf-8').replace('pe_core_reference.py','pe_core_visual_reference.py')
    start=readme.index('PORTABLE FINAL-RECIPE REPRODUCTION' if 'PORTABLE FINAL-RECIPE REPRODUCTION' in readme else 'Read script --help / argparse definitions')
    end=readme.index('4. REPORT RESULTS WITHOUT RETRAINING')
    readme=readme[:start]+PORTABLE_GUIDE+'\n'+readme[end:]
    if 'python report_analysis/build_cycle_evidence.py' not in readme:
        readme=readme.replace('python report_analysis/build_panels.py','python report_analysis/build_panels.py\n  python report_analysis/build_cycle_evidence.py')
    (CODE/'README.txt').write_text(readme,encoding='utf-8')
    # The original inference adapter imports open_clip; make that dependency explicit.
    req=CODE/'requirements-reproduction.txt'
    req.write_text('-r scripts/experiments/requirements-visual.txt\nopen_clip_torch==3.3.0\n-r requirements-analysis.txt\n',encoding='utf-8')
    comparison=json.loads((ROOT/'.local/portable_adapter_check/comparison.json').read_text(encoding='utf-8'))
    comparison.update(scope='CPU prediction phase checked against archived heads/features; no fresh encoder extraction or full refit executed in this revision.')
    (CODE/'checks/portable_prediction_adapter.json').write_text(json.dumps(comparison,indent=2),encoding='utf-8')
    for command in [['reproduce_final.py','check'],['evaluate_report.py']]:
        subprocess.run([sys.executable,'-X','utf8',*command],cwd=CODE,check=True)
    # Generated bytecode is never part of the hand-in.
    for p in list(CODE.rglob('__pycache__')):
        resolved=p.resolve();assert resolved.is_relative_to(CODE.resolve())
        shutil.rmtree(resolved)
    manifest={p.relative_to(CODE).as_posix():{'bytes':p.stat().st_size,'sha256':sha(p)} for p in sorted(CODE.rglob('*')) if p.is_file() and p.name!='MANIFEST.json'}
    (CODE/'MANIFEST.json').write_text(json.dumps(manifest,indent=2)+'\n',encoding='utf-8')
    subprocess.run([sys.executable,'-X','utf8','verify_submission.py'],cwd=CODE,check=True)
    target=ROOT/'submission/English/code.zip';temp=target.with_suffix('.cycle.zip')
    with zipfile.ZipFile(temp,'w',zipfile.ZIP_DEFLATED,compresslevel=6) as z:
        for p in sorted(CODE.rglob('*')):
            if p.is_file():z.write(p,p.relative_to(CODE).as_posix())
    with zipfile.ZipFile(temp) as z:
        assert z.testzip() is None
        assert all(hashlib.sha256(z.read(name)).hexdigest()==entry['sha256'] for name,entry in manifest.items())
    temp.replace(target)
    release=ROOT/'submission/release_manifest.json';m=json.loads(release.read_text(encoding='utf-8'))
    m['validation']['manifest_files']=len(manifest)
    m['validation']['portable_prediction_adapter_max_abs_error']=comparison['max_abs_difference_from_archived_submission']
    m['validation']['encoder_extraction_rerun']=False;m['validation']['full_refit_rerun']=False
    release.write_text(json.dumps(m,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    subprocess.run([sys.executable,'-X','utf8',str(ROOT/'scripts/refresh_submission_reports.py')],cwd=ROOT,check=True)


